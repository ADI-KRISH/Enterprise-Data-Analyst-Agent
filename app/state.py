"""LangGraph agent state (CLAUDE.md "Agent state").

Nodes return partial updates. `trace` is append-only (each node adds its own events) and
`timings` accumulates milliseconds per node name (nodes in retry loops run several times).
Everything in the state is JSON-serialisable; secrets are never stored here.
"""

from __future__ import annotations

import operator
from typing import Annotated, Any, Literal, TypedDict

GuardCategory = Literal["analytics", "off_topic", "unsafe_write", "prompt_injection", "pii_request"]
Intent = Literal["aggregate", "trend", "compare", "rank", "diagnose", "definition"]


def merge_timings(left: dict[str, float] | None, right: dict[str, float] | None) -> dict[str, float]:
    out = dict(left or {})
    for node, ms in (right or {}).items():
        out[node] = round(out.get(node, 0.0) + ms, 1)
    return out


class QueryState(TypedDict, total=False):
    """One planned query. Non-diagnose questions have exactly one; diagnose up to three."""

    id: int
    purpose: str
    description: str
    sql: str | None  # as generated by the LLM (untrusted)
    validated_sql: str | None  # normalized SQL returned by the validator: what executes
    status: Literal["pending", "invalid", "valid", "executed", "failed"]
    errors: list[str]  # internal feedback for the SQL generator, never shown to users
    error_code: str | None
    result: dict[str, Any] | None  # {columns, records, row_count, truncated}


class AgentState(TypedDict, total=False):
    request_id: str
    question: str
    # input guard
    guard_category: GuardCategory | None
    refused: bool
    refusal_reason: str | None
    # understanding
    intent: Intent | None
    entities: list[dict[str, str]]
    metrics: list[str]
    filters: list[dict[str, str]]
    group_by: list[str]
    top_n: int | None
    time_range: dict[str, Any] | None
    undefined_metrics: list[str]
    clarification_reason: str | None
    # retrieval / planning
    retrieved_context: dict[str, Any] | None
    plan: dict[str, Any] | None
    queries: list[QueryState]
    # SQL loop
    sql: str | None
    validation_errors: list[str]
    sql_attempts: int
    verify_retries: int
    result_df: dict[str, Any] | None  # {columns, records, row_count, truncated}
    verification: dict[str, Any] | None
    # outputs
    analysis: dict[str, Any] | None
    chart_spec: dict[str, Any] | None
    answer: str | None
    grounded: bool | None
    grounding: dict[str, Any] | None
    response_attempts: int
    needs_clarification: bool
    clarification_question: str | None
    output_blocked: str | None
    error: str | None  # internal reason code; users only ever see the generic message
    trace: Annotated[list[dict[str, Any]], operator.add]
    timings: Annotated[dict[str, float], merge_timings]
